`timescale 1ns/1ps
module tb_render;
 reg clk=0;always #5 clk=~clk;reg rst_n=0,frame_tick=0,link=1,fire=0,press=0,restart=0;
 reg signed[3:0] mx=0,my=0;reg[2:0] aim=2;
 wire[7:0] px,ex,bx,score;wire[6:0] py,ey,by;wire bullet,over;wire[2:0] dir;
 flight_game game(clk,rst_n,frame_tick,link,mx,my,aim,fire,press,restart,px,ex,bx,py,ey,by,bullet,dir,score,over);
 reg[7:0] x;reg[6:0] y;wire[1:0] r,g,b;
 pixel_renderer pixels(x,px,ex,bx,y,py,ey,by,bullet,dir,score,over,link,r,g,b);
 task tick;begin @(negedge clk);frame_tick=1;@(negedge clk);frame_tick=0;end endtask
 task render(input string name);
 integer file,xx,yy;begin
  file=$fopen(name,"w");$fwrite(file,"P3\n160 120\n255\n");
  for(yy=0;yy<120;yy=yy+1)for(xx=0;xx<160;xx=xx+1)begin
   x=xx[7:0];y=yy[6:0];#1;
   if(^{r,g,b}===1'bx)$fatal(1,"unknown renderer output");
   $fwrite(file,"%0d %0d %0d\n",r*85,g*85,b*85);
  end
  $fclose(file);
 end endtask
 integer n;
 initial begin
  repeat(3)@(negedge clk);rst_n=1;
  render("test/output/start.ppm");
  my=-3;repeat(10)tick();my=0;fire=1;tick();fire=0;repeat(10)tick();
  render("test/output/firing.ppm");
  n=0;while(score==0 && n<60)begin tick();n=n+1;end
  if(score!=1)$fatal(1,"rendered demo hit not reached");
  render("test/output/hit.ppm");
  restart=1;tick();restart=0;my=-3;repeat(10)tick();my=0;
  n=0;while(!over && n<160)begin tick();n=n+1;end
  if(!over)$fatal(1,"rendered demo gameover not reached");
  render("test/output/game-over.ppm");
  link=0;render("test/output/disconnected.ppm");
  $display("PASS: five frames generated by game and pixel RTL, including natural hit/gameover");$finish;
 end
endmodule
